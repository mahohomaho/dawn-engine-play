const assert=require('node:assert/strict');
require('./data.js');require('./catalog.js');require('./v3-data.js');require('./engine.js');require('./v3-engine.js');
const map=require('./skill-map.js'),data=global.GameData,{GameEngine,newState}=global.GuildEngine;
const game=new GameEngine(newState(77));
game.dispatch('CHOOSE_START',{job:'warrior',pet:'dog'});
const layout=map.create(data),all=[...data.trees,...Object.values(data.jobTrees)].flatMap(group=>group.nodes);
assert.equal(layout.groups.length,17);
assert.equal(layout.positions.size,all.length+data.hiddenNodes.length);
assert.equal(new Set(all.map(node=>JSON.stringify(layout.position(node)))).size,all.length);
const first=map.visible(game,data);
assert(first.some(node=>node.nodeId==='S01'));
assert(first.some(node=>node.nodeId==='S35'));
assert(first.some(node=>node.nodeId==='S02'));
assert(!map.revealed(game,data.nodeMap.S02));
assert(!first.some(node=>node.nodeId==='S66'));
game.state.run.gold=1000;
assert.equal(game.dispatch('BUY_SKILL',{id:'S01'}).type,'skill');
const grown=map.visible(game,data);
assert(grown.some(node=>node.nodeId==='S02'));
assert(grown.some(node=>node.nodeId==='S01'));
assert(map.revealed(game,data.nodeMap.S02));
assert(map.prominent(data.nodeMap.S05));
assert(!map.prominent(data.nodeMap.S01));
game.state.run.bookUsed.push('I33');
assert(map.visible(game,data).some(node=>node.nodeId==='S66'));
console.log('Unified skill map checks passed');
